#!/usr/bin/env bash
# Script: Copy backend/_shared into every deployable Python service
#
# Local hot-reload mounts a single service directory as the Lambda's code, and
# pip installs that service's requirements into the same directory, so imports
# cannot reach outside the service folder. Shared code is therefore edited once
# in backend/_shared and copied into each service's lib/ by this script.
#
# Run it after editing anything in backend/_shared. bin/start-dev.sh and
# bin/deploy-backend.sh call it automatically.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
SHARED_DIR="$PROJECT_ROOT/backend/_shared"

if [[ ! -d "$SHARED_DIR" ]]; then
    echo "  ✗ No backend/_shared directory found"
    exit 1
fi

synced=0
for service_dir in "$PROJECT_ROOT"/backend/*/; do
    service="$(basename "$service_dir")"

    # Folders starting with _ or . are not deployed by Terraform.
    [[ "$service" == _* || "$service" == .* ]] && continue
    # Python services only; Java and Node.js services share code differently.
    [[ -f "$service_dir/requirements.txt" ]] || continue

    mkdir -p "$service_dir/lib"
    for module in "$SHARED_DIR"/*.py; do
        target="$service_dir/lib/$(basename "$module")"
        {
            echo "# Generated by bin/sync-shared.sh - do not edit."
            echo "# Source of truth: backend/_shared/$(basename "$module")"
            cat "$module"
        } > "$target"
    done

    # Make lib/ a package. Shared modules import each other relatively, so
    # every service sees exactly one copy of each class (a module loaded under
    # two names would give two distinct HttpError types, and handlers would
    # fail to catch one of them).
    cat > "$service_dir/lib/__init__.py" <<'PY'
"""Shared modules copied from backend/_shared by bin/sync-shared.sh - do not edit."""
PY

    synced=$((synced + 1))
    echo "  ✓ synced shared modules into backend/$service/lib"
done

echo "  Shared modules synced into $synced service(s)"
